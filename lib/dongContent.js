// 같은 trait 안에서도 문장 변형(variant)을 섞어 지역명만 바꾼 중복 본문을 피합니다.
const meta = require('../data/dong-meta');

// 받침 유무에 따른 조사 선택 (은/는)
function eun(word) {
  const ch = word.charCodeAt(word.length - 1);
  const hasJong = ch >= 0xac00 && ch <= 0xd7a3 && (ch - 0xac00) % 28 !== 0;
  return word + (hasJong ? '은' : '는');
}

function hash(s) {
  let h = 0;
  for (const ch of String(s)) h = (h * 31 + ch.charCodeAt(0)) % 9973;
  return h;
}
function pick(arr, seed) { return arr[hash(seed) % arr.length]; }

// 이름·목록 기반 trait 판정
function traitOf(cityName, dongName) {
  const o = meta.traits[`${cityName}:${dongName}`] || meta.traits[dongName];
  if (o) return o;
  if (/읍$/.test(dongName)) return 'eup';
  if (/면$/.test(dongName)) return 'myeon';
  return 'residential';
}

