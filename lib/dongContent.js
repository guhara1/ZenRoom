function build({ city, gu, name, region }) {
  const trait = traitOf(city.name, name);
  const t = BODY[trait];
  const seed = city.slug + name;
  const label = TRAIT_LABEL[trait];
  const note = meta.notes[`${city.name}:${name}`] || meta.notes[name] || null;

  const lead = `${note ? note + ' ' : ''}${pick(t.feature, seed)(name, city.name)}`;
  const isEupMyeon = trait === 'eup' || trait === 'myeon';
  const dedup = isEupMyeon
    ? `${name} 안의 리 단위 세부 주소는 별도 페이지로 나누지 않고 이 페이지에서 함께 안내합니다. 세부 주소까지 알려주시면 진입로와 이동 기준을 예약 전에 확인해 드립니다.`
    : `1동·2동·3동처럼 번호로 나뉜 세부 행정동은 생활권이 같아 이 대표 페이지에서 함께 안내합니다. 검색 노출 목적으로 같은 내용을 반복하는 페이지는 만들지 않으며, 세부 동 주소 그대로 문의하시면 됩니다.`;

  const sections = [
    ['건물·숙소 유형별 확인', pick(t.building, seed + 'b')(name, city.name)],
    ['이동·예약 시간 기준', pick(t.move, seed + 'm')(name, city.name)],
    ['세부 주소 안내 기준', dedup],
  ];

  const faq = [
    [`${name}은 언제 예약하는 것이 좋나요?`,
      trait === 'myeon' || trait === 'tourist' || trait === 'eup'
        ? '외곽 구간이 포함될 수 있어 몇 시간 이상 여유를 두고 문의하시면 원하는 시간에 맞추기 쉽습니다. 야간·심야는 사전 협의가 필요합니다.'
        : '당일 예약도 조율 가능한 경우가 많지만, 저녁 시간대는 문의가 몰려 미리 예약하시면 원하는 시간을 맞추기 쉽습니다.'],
    [`${name}에서 가까운 생활권 기준은 어디인가요?`,
      `${city.name}의 대표 생활권(${city.zones.slice(0, 3).join('·')}) 기준으로 함께 안내됩니다. 정확한 주소를 알려주시면 가장 가까운 기준으로 확인해 드립니다.`],
  ];

  return { trait, label, lead, sections, faq, checks: t.checks, uses: t.uses };
}

module.exports = { build, traitOf, TRAIT_LABEL };
